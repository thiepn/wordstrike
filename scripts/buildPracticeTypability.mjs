execFileSync(process.execPath, [path.join(root, "scripts", "buildPracticeCorpus.mjs"), "--validate"], { stdio: "ignore" });
execFileSync(process.execPath, [path.join(root, "scripts", "buildPracticeIndexes.mjs"), "--validate"], { stdio: "ignore" });

const corpusManifest = await readJson(path.join(practiceRoot, "manifests", "en-v1.manifest.json"));
const indexManifest = await readJson(path.join(practiceRoot, "indexes", "en-v1", "manifest.json"));
const sourceRegistry = await readJson(path.join(practiceRoot, "provenance", "sources.json"));
const partitionArtifacts = {};
for (const partition of PRACTICE_CORPUS_PARTITIONS) partitionArtifacts[partition] = await readJson(path.join(practiceRoot, partition, "en-v1.json"));

// Optional frequency references are separate governed artifacts. None exists in the current PL6 provenance release.
const frequencyPath = path.join(practiceRoot, "provenance", "frequency", "en-v1.frequency.json");
const frequencyReference = await exists(frequencyPath) ? await readJson(frequencyPath) : null;
const build = buildPracticeTypabilityArtifacts({ corpusManifest, indexManifest, partitionArtifacts, sourceRegistry, frequencyReference });
const referenceValidation = validatePracticeTypabilityReference(build.reference);
if (!referenceValidation.valid) throw new Error(`Practice typability reference failed validation: ${JSON.stringify(referenceValidation.errors)}`);
const output = createOutput(build, corpusManifest, indexManifest);
validateManifest(output.manifest, build.reference);
const modelDir = path.join(modelsRoot, "en-v1");
if (validateOnly) await validateCheckedIn(modelDir, output);
else await replaceSafely(modelDir, output);

console.log(`Practice typability ${validateOnly ? "validated" : "built"}: ${corpusManifest.corpusId} v${corpusManifest.corpusVersion}`);
console.log(`  model=${PRACTICE_TYPABILITY_MODEL_VERSION} feature=${PRACTICE_TEXT_FEATURE_VERSION} reference=${PRACTICE_TYPABILITY_REFERENCE_VERSION}`);
console.log(`  fit=training(${build.reference.referenceItemCount}) scored=${build.diagnostics.scoredItemCount} holdoutScored=false`);
console.log(`  corpusChecksum=${corpusManifest.buildChecksum}`);
console.log(`  indexChecksum=${indexManifest.indexChecksum}`);
console.log(`  frequencyReference=${build.frequencyMetadata.referenceVersion ?? "none"}`);
